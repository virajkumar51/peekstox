/** Reliable institutional exchange rates against 1 USD base */
export const USD_RATES: Record<string, number> = {
  USD: 1.0,
  INR: 86.85,
  EUR: 0.92,
  GBP: 0.79,
  JPY: 154.5,
  CAD: 1.40,
  AUD: 1.55,
  CHF: 0.89,
};

export function getBaseCurrencySymbol(currency: string): string {
  switch ((currency || 'USD').toUpperCase()) {
    case 'USD': return '$';
    case 'EUR': return '€';
    case 'GBP':
    case 'GBP_PENCE':
    case 'GBX': return '£';
    case 'INR': return '₹';
    case 'JPY': return '¥';
    case 'CAD': return 'C$';
    case 'AUD': return 'A$';
    case 'CHF': return 'CHF ';
    default: return `${currency} `;
  }
}

/**
 * Converts price to baseCurrency while clearly preserving original market values.
 * Never alters underlying stock prices or financial calculations.
 */
export function convertAndFormatPrice(
  price: number,
  stockCurrency: string = 'USD',
  baseCurrency: string = 'USD',
  options?: { showOriginalBadge?: boolean }
): string {
  if (price === undefined || price === null || isNaN(price)) return '—';

  const stockCurrNorm = (stockCurrency || 'USD').toUpperCase();
  const baseCurrNorm = (baseCurrency || 'USD').toUpperCase();

  // Normalize GBP pence (GBp / GBX) if applicable
  let priceInUsd = price;
  if (stockCurrNorm === 'GBX' || stockCurrNorm === 'GBP_PENCE') {
    priceInUsd = (price / 100) / (USD_RATES['GBP'] || 0.79);
  } else if (USD_RATES[stockCurrNorm]) {
    priceInUsd = price / USD_RATES[stockCurrNorm];
  }

  // Convert to user selected display currency
  let convertedPrice = priceInUsd;
  if (USD_RATES[baseCurrNorm]) {
    convertedPrice = priceInUsd * USD_RATES[baseCurrNorm];
  }

  const baseSym = getBaseCurrencySymbol(baseCurrNorm);
  const stockSym = getBaseCurrencySymbol(stockCurrNorm);

  const isIntCurr = (c: string) => c === 'JPY' || c === 'KRW';

  const convertedStr = `${baseSym}${convertedPrice.toLocaleString('en-US', {
    minimumFractionDigits: isIntCurr(baseCurrNorm) ? 0 : 2,
    maximumFractionDigits: isIntCurr(baseCurrNorm) ? 0 : 2,
  })}`;

  const originalStr = `${stockSym}${price.toLocaleString('en-US', {
    minimumFractionDigits: isIntCurr(stockCurrNorm) ? 0 : 2,
    maximumFractionDigits: isIntCurr(stockCurrNorm) ? 0 : 2,
  })}`;

  // If display currency matches market listing currency, show exact price
  if (stockCurrNorm === baseCurrNorm) {
    return originalStr;
  }

  // If caller requested raw converted string without suffix
  if (options?.showOriginalBadge === false) {
    return convertedStr;
  }

  // Distinctly show converted price with clear original market notation
  return `${convertedStr} (Orig: ${originalStr})`;
}

/**
 * Returns structured details about the converted vs original price
 */
export function getPriceConversionDetails(
  price: number,
  stockCurrency: string = 'USD',
  baseCurrency: string = 'USD'
) {
  const stockCurrNorm = (stockCurrency || 'USD').toUpperCase();
  const baseCurrNorm = (baseCurrency || 'USD').toUpperCase();
  const isConverted = stockCurrNorm !== baseCurrNorm;

  let priceInUsd = price;
  if (stockCurrNorm === 'GBX' || stockCurrNorm === 'GBP_PENCE') {
    priceInUsd = (price / 100) / (USD_RATES['GBP'] || 0.79);
  } else if (USD_RATES[stockCurrNorm]) {
    priceInUsd = price / USD_RATES[stockCurrNorm];
  }

  let convertedPrice = priceInUsd;
  if (USD_RATES[baseCurrNorm]) {
    convertedPrice = priceInUsd * USD_RATES[baseCurrNorm];
  }

  const baseSym = getBaseCurrencySymbol(baseCurrNorm);
  const stockSym = getBaseCurrencySymbol(stockCurrNorm);
  const isIntCurr = (c: string) => c === 'JPY' || c === 'KRW';

  return {
    isConverted,
    originalPrice: price,
    originalCurrency: stockCurrNorm,
    originalFormatted: `${stockSym}${price.toLocaleString('en-US', {
      minimumFractionDigits: isIntCurr(stockCurrNorm) ? 0 : 2,
      maximumFractionDigits: isIntCurr(stockCurrNorm) ? 0 : 2,
    })}`,
    convertedPrice,
    convertedCurrency: baseCurrNorm,
    convertedFormatted: `${baseSym}${convertedPrice.toLocaleString('en-US', {
      minimumFractionDigits: isIntCurr(baseCurrNorm) ? 0 : 2,
      maximumFractionDigits: isIntCurr(baseCurrNorm) ? 0 : 2,
    })}`,
  };
}
